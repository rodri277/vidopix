export function renderNotices(packages) {
  const rows = packages.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`);
  const sections = packages.map((p) => {
    const marks = fence(p.text);
    return `## ${p.name} ${p.version}\n\nLicense: ${p.license}\n\n${marks}text\n${p.text}\n${marks}\n`;
  });
  return [
    HEADER,
    '| Package | Version | License |\n| --- | --- | --- |\n' + rows.join('\n') + '\n',
    ...sections,
  ].join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const { problems, packages } = collectShipped();
  if (problems.length > 0) {
    console.error(`Cannot attribute everything in the build:\n- ${problems.join('\n- ')}`);
    process.exit(1);
  }
  const expected = renderNotices(packages);
  if (!check) {
    writeFileSync(NOTICES_FILE, expected);
    return;
  }
  const current = existsSync(NOTICES_FILE) ? readFileSync(NOTICES_FILE, 'utf8') : '';
  if (current !== expected) {
    console.error(
      'THIRD_PARTY_LICENSES.md does not match the packages in the build. Run `pnpm licenses` and commit it.',
    );
    process.exit(1);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
