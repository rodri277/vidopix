// Builds THIRD_PARTY_LICENSES.md from what the production build really ships, not from
// package.json: the source maps name every package that ended up in a bundle (with its exact
// version, so two copies of one package both show up) and every font file is traced back to
// the package it was copied from. Anything in the build that cannot be traced fails the run.
//
//   node tools/third-party-licenses.mjs          rewrite the file (after `pnpm build`)
//   node tools/third-party-licenses.mjs --check  fail if the file does not match the build
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { basename, dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const web = join(root, 'apps', 'web');
const DIST = join(web, 'dist');
export const NOTICES_FILE = join(root, 'THIRD_PARTY_LICENSES.md');

/** Files the build writes that are this project's own (see the notices plugin in vite.config.ts). */
const OWN_FILES = new Set([
  'index.html',
  'manifest.webmanifest',
  'third-party-licenses.txt',
  'privacy.txt',
]);
const OWN_SOURCES = [join(web, 'src'), join(root, 'packages', 'core', 'src')];

/**
 * Code in the build that does not come from a file in node_modules: modules generated by a
 * plugin at build time. Each one is attributed to the package that writes it.
 */
const GENERATED = [
  { map: /.*/, source: /virtual:pwa-register$/, from: [], name: 'vite-plugin-pwa' },
  { map: /^sw\.js\.map$/, source: /\/sw\.js$/, from: ['vite-plugin-pwa'], name: 'workbox-build' },
];

const LICENSE_FILE = /^(licen[cs]e|copying)(\.(md|txt))?$/i;

/** The package directory and name for a path inside node_modules, or null. */
export function packageFromPath(path) {
  const marker = `${sep}node_modules${sep}`;
  const at = path.lastIndexOf(marker);
  if (at < 0) return null;
  const parts = path.slice(at + marker.length).split(sep);
  const segments = parts[0]?.startsWith('@') ? 2 : 1;
  if (parts.length <= segments) return null;
  const name = parts.slice(0, segments).join('/');
  return { name, dir: path.slice(0, at + marker.length) + parts.slice(0, segments).join(sep) };
}

/** `inter-latin-wght-normal-Dx4kXJAl.woff2` → `inter-latin-wght-normal.woff2`. */
export function withoutHash(fileName) {
  return fileName.replace(/-[\w-]{8}(\.[a-z0-9]+)$/i, '$1');
}

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)],
  );
}

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function resolvePackageDir(name, from) {
  let base = join(web, 'package.json');
  for (const step of [...from, name]) {
    base = join(dirname(createRequire(base).resolve(`${step}/package.json`)), 'package.json');
  }
  return dirname(base);
}

/**
 * The installed package a mapped source belongs to. Most maps are relative to themselves, but
 * the Workbox runtime that vite-plugin-pwa writes next to sw.js is mapped relative to apps/web.
 */
function installedPackage(mapFile, sourceRoot, source) {
  for (const base of [dirname(mapFile), web]) {
    const pkg = packageFromPath(resolve(base, sourceRoot, source));
    if (pkg && existsSync(join(pkg.dir, 'package.json'))) return pkg;
  }
  return null;
}

/** Packages whose code is in a source-mapped bundle. Fails on a source it cannot place. */
function packagesInBundles(dist, files, problems) {
  const found = new Map();
  for (const mapFile of files.filter((file) => file.endsWith('.map'))) {
    const map = readJson(mapFile);
    const mapName = basename(mapFile);
    for (const source of map.sources) {
      const path = resolve(dirname(mapFile), map.sourceRoot ?? '', source);
      if (packageFromPath(path)) {
        const pkg = installedPackage(mapFile, map.sourceRoot ?? '', source);
        if (pkg) found.set(pkg.dir, pkg.name);
        else problems.push(`${relative(dist, mapFile)}: "${source}" is not an installed package`);
        continue;
      }
      if (OWN_SOURCES.some((own) => path.startsWith(own + sep))) continue;
      const generated = GENERATED.find((g) => g.map.test(mapName) && g.source.test(source));
      if (generated) {
        found.set(resolvePackageDir(generated.name, generated.from), generated.name);
        continue;
      }
      problems.push(`${relative(dist, mapFile)}: cannot tell where "${source}" comes from`);
    }
  }
  return found;
}

/** The package each font in the build was copied from, searched among the app's dependencies. */
function packagesOfFonts(dist, files, problems) {
  const candidates = Object.keys(readJson(join(web, 'package.json')).dependencies ?? {})
    .filter((name) => !name.startsWith('@vidopix/'))
    .map((name) => ({ name, dir: resolvePackageDir(name, []) }))
    .map((pkg) => ({ ...pkg, files: new Set(walk(pkg.dir).map((file) => basename(file))) }));
  const found = new Map();
  for (const font of files.filter((file) => /\.(woff2?|ttf|otf)$/.test(file))) {
    const original = withoutHash(basename(font));
    const owner = candidates.find((pkg) => pkg.files.has(original));
    if (owner) found.set(owner.dir, owner.name);
    else problems.push(`${relative(dist, font)}: no dependency ships "${original}"`);
  }
  return found;
}

/** Every other file must be the project's own: copied from public/ or written by the build. */
function checkOtherFiles(dist, files, problems) {
  for (const file of files) {
    if (/\.(map|js|css|woff2?|ttf|otf)$/.test(file)) continue;
    const path = relative(dist, file);
    if (OWN_FILES.has(path) || existsSync(join(web, 'public', path))) continue;
    problems.push(`${path}: not from public/ and not a known build output`);
  }
}

function describe(dir, name, problems) {
  const manifest = readJson(join(dir, 'package.json'));
  const licenseFile = readdirSync(dir).find((file) => LICENSE_FILE.test(file));
  if (!licenseFile) problems.push(`${name}@${manifest.version}: no license file in the package`);
  return {
    name,
    version: manifest.version,
    license: typeof manifest.license === 'string' ? manifest.license : 'see text',
    text: licenseFile ? readFileSync(join(dir, licenseFile), 'utf8').trim() : '',
  };
}

/** The packages in the current build, sorted, or the list of things that could not be traced. */
export function collectShipped(dist = DIST) {
  if (!existsSync(dist))
    return { problems: [`${relative(root, dist)} is missing: run \`pnpm build\` first`] };
  const problems = [];
  const files = walk(dist);
  const dirs = new Map([
    ...packagesInBundles(dist, files, problems),
    ...packagesOfFonts(dist, files, problems),
  ]);
  checkOtherFiles(dist, files, problems);
  const packages = [...dirs]
    .map(([dir, name]) => describe(dir, name, problems))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  return { problems, packages };
}

function fence(text) {
  const longest = Math.max(2, ...(text.match(/`+/g) ?? []).map((run) => run.length));
  return '`'.repeat(longest + 1);
}

